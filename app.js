/**
 * Formats a date as DD/MM/YYYY.
 * @param {Date|string} date
 * @returns {string}
 */
function formatDate(date) {
    if (!date) return '';
    const d = new Date(date);
    return `${String(d.getDate()).padStart(2, '0')}/${String(d.getMonth() + 1).padStart(2, '0')}/${d.getFullYear()}`;
}

/**
 * Formats a short date DD/MM (no year).
 * @param {Date|string} date
 * @returns {string}
 */
function formatDateShort(date) {
    if (!date) return '';
    const d = new Date(date);
    return `${String(d.getDate()).padStart(2, '0')}/${String(d.getMonth() + 1).padStart(2, '0')}`;
}

/**
 * Formats the time as HH:MM.
 * @param {Date} date
 * @returns {string}
 */
function formatTime(date) {
    if (!date) return '';
    return date.toLocaleTimeString('en-GB', { hour: '2-digit', minute: '2-digit' });
}

/**
 * Formats a market value in EUR for compact display.
 * E.g. 45000000 → "€ 45.0M", 500000 → "€ 500K"
 *
 * @param {number} v - Value in EUR
 * @returns {string}
 */
function formatMarketValue(v) {
    if (v >= 1000000) return `\u20AC ${(v / 1000000).toFixed(1)}M`;
    if (v >= 1000) return `\u20AC ${Math.round(v / 1000)}K`;
    return `\u20AC ${v}`;
}

function formatMarketValueBRL(v) {
    const brl = v * EUR_TO_BRL;
    if (brl >= 1000000) return `R$ ${(brl / 1000000).toFixed(1)}M`;
    if (brl >= 1000) return `R$ ${Math.round(brl / 1000)}K`;
    return `R$ ${Math.round(brl)}`;
}


