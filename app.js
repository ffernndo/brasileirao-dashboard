/**
 * Renders the league-wide KPI cards.
 * Always the same regardless of the selected team.
 */
function renderKPIs(standings, allMatches) {
    if (!standings || standings.length === 0) {
        return `<div class="kpi-grid kpi-empty-wrapper">
            <div class="kpi-empty">No data loaded. Data is updated automatically every day.</div>
        </div>`;
    }

    const kpi = (label, value, detail = '', color = '') =>
        `<div class="kpi-card">
            <div class="kpi-label">${label}</div>
            <div class="kpi-value small">${value}</div>
            ${detail ? `<div class="kpi-detail" style="color:${color || 'var(--text-secondary)'}">${detail}</div>` : ''}
        </div>`;

    const selectedTeam = appState.selectedTeam;

    // ── KPIs for the selected team ────────────────────────────────
    if (selectedTeam !== 'All teams') {
        const t = standings.find(s => s.name === selectedTeam);
        if (!t) return '';

        const maxPts = t.played * 3 || 1;
        const aprov = Math.round(t.points / maxPts * 100);
        const aprovColor = aprov >= 60 ? 'var(--accent-green)' : aprov >= 40 ? 'var(--accent-yellow)' : 'var(--accent-red)';
        const sg = t.goalsFor - t.goalsAgainst;
        const sgStr = sg > 0 ? `+${sg}` : String(sg);
        const sgColor = sg > 0 ? 'var(--accent-green)' : sg < 0 ? 'var(--accent-red)' : 'var(--text-secondary)';

        // Current streak
        const sorted = [...t.matches].sort((a, b) => new Date(b.date) - new Date(a.date));
        let streakType = '', streakCount = 0;
        for (const m of sorted) {
            const res = m.score > m.conceded ? 'W' : m.score === m.conceded ? 'D' : 'L';
            if (!streakType) { streakType = res; streakCount = 1; }
            else if (res === streakType) streakCount++;
            else break;
        }
        const streakLabel = streakCount > 0 ? `${streakCount}${streakType}` : '-';
        const streakColor = streakType === 'W' ? 'var(--accent-green)' : streakType === 'L' ? 'var(--accent-red)' : 'var(--accent-yellow)';

        const homePts = t.homeWins * 3 + t.homeDraws;
        const awayPts = t.awayWins * 3 + t.awayDraws;

        return `
            <div class="kpi-grid">
                ${kpi('Points', t.points, `${t.played} played • ${t.wins}W ${t.draws}D ${t.losses}L`)}
                ${kpi('Points %', `${aprov}%`, `${t.points} of ${t.played * 3} possible`, aprovColor)}
                ${kpi('Position', `${t.position}`, `of 20 teams`)}
                ${kpi('Current Streak', streakLabel, `latest results`, streakColor)}
            </div>
            <div class="kpi-grid" style="margin-top:0">
                ${kpi('Goals', `${t.goalsFor} / ${t.goalsAgainst}`, 'for / against')}
                ${kpi('Goal Difference', sgStr, `${t.goalsFor} GF • ${t.goalsAgainst} GA`, sgColor)}
                ${kpi('Home', `${homePts} pts`, `${t.homeWins}W ${t.homeDraws}D ${t.homeLosses}L`, 'var(--accent-blue)')}
                ${kpi('Away', `${awayPts} pts`, `${t.awayWins}W ${t.awayDraws}D ${t.awayLosses}L`, 'var(--accent-blue)')}
            </div>
        `;
    }

    // ── League-wide KPIs ─────────────────────────────────────
    const finished   = allMatches.filter(m => m.intHomeScore !== null && m.intHomeScore !== undefined && m.intHomeScore !== '').length;
    const totalGoals = allMatches.reduce((s, m) =>
        s + (parseInt(m.intHomeScore) || 0) + (parseInt(m.intAwayScore) || 0), 0);
    const avgGoals   = finished > 0 ? (totalGoals / finished).toFixed(2) : '0.0';

    const leader      = standings[0];
    const bestAttack  = standings.reduce((max, t) => t.goalsFor > max.goalsFor ? t : max);
    const bestDefense = standings.reduce((min, t) => t.goalsAgainst < min.goalsAgainst ? t : min);

    let bestStreak = { team: '', streak: 0 };
    standings.forEach(team => {
        const sorted = [...team.matches].sort((a, b) => new Date(b.date) - new Date(a.date));
        let streak = 0;
        for (const m of sorted) { if (m.score > m.conceded) streak++; else break; }
        if (streak > bestStreak.streak) bestStreak = { team: team.name, streak };
    });

    const topHomeTeam = standings.reduce((max, t) =>
        (t.homeWins * 3 + t.homeDraws) > (max.homeWins * 3 + max.homeDraws) ? t : max);
    const topAwayTeam = standings.reduce((max, t) =>
        (t.awayWins * 3 + t.awayDraws) > (max.awayWins * 3 + max.awayDraws) ? t : max);

    return `
        <div class="kpi-grid">
            ${kpi('Matches Played', finished, `${totalGoals} goals in total`)}
            ${kpi('Goals per Match', avgGoals, 'average')}
            ${kpi('Leader', leader.name, `${leader.points} pts • ${leader.played} P`)}
            ${kpi('Longest Win Streak', bestStreak.streak > 0 ? `${bestStreak.streak}W` : '-', bestStreak.team, 'var(--accent-green)')}
        </div>
        <div class="kpi-grid" style="margin-top:0">
            ${kpi('Best Attack', bestAttack.name, `${bestAttack.goalsFor} goals scored`, 'var(--accent-green)')}
            ${kpi('Best Defence', bestDefense.name, `${bestDefense.goalsAgainst} goals conceded`, 'var(--accent-green)')}
            ${kpi('Best Home Team', topHomeTeam.name, `${topHomeTeam.homeWins * 3 + topHomeTeam.homeDraws} pts at home`, 'var(--accent-blue)')}
            ${kpi('Best Away Team', topAwayTeam.name, `${topAwayTeam.awayWins * 3 + topAwayTeam.awayDraws} pts away`, 'var(--accent-blue)')}
        </div>
    `;
}

/**
 * Renders the standings table with coloured zones (no bullets).
 * Zones are shown only by the row's left border.
 *
 * @param {Array<TeamStats>} standings - Sorted standings
 * @param {Object} teamBadges - Badge map (unused, kept for compatibility)
 * @param {string} selectedTeam - Team selected for highlighting
 * @returns {string} Table HTML
 */
function renderStandings(standings, teamBadges, selectedTeam) {
    if (!standings || standings.length === 0) {
        return `<div class="standings-wrapper"><div class="standings-empty">No data available.</div></div>`;
    }

    let html = `<div class="standings-wrapper"><table class="standings-table"><thead><tr>
        <th>#</th><th></th><th>Team</th><th class="th-center">Pts</th><th class="th-center">P</th><th class="th-center hide-mobile">W</th><th class="th-center hide-mobile">D</th><th class="th-center hide-mobile">L</th><th class="th-center hide-mobile">GF</th><th class="th-center hide-mobile">GA</th><th class="th-center">GD</th><th class="th-center">Last 5</th><th class="th-center hide-mobile">Last</th>
    </tr></thead><tbody>`;

    standings.forEach(team => {
        // 2026 standings zone (CSS class only, for the left border)
        let zoneClass = '';
        if (team.position <= 4)       zoneClass = 'zone-libertadores';
        else if (team.position === 5) zoneClass = 'zone-pre-libertadores';
        else if (team.position <= 11) zoneClass = 'zone-sudamericana';
        else if (team.position >= 17) zoneClass = 'zone-rebaixamento';

        const highlighted = selectedTeam !== 'All teams' && team.name === selectedTeam
            ? 'highlighted' : '';

        // Last 5 matches (form dots)
        const last5 = [...team.matches]
            .sort((a, b) => new Date(b.date) - new Date(a.date))
            .slice(0, 5)
            .reverse();

        let formHtml = '<div class="form-dots">';
        last5.forEach(m => {
            if (m.score > m.conceded)      formHtml += '<div class="form-dot win" title="Win"></div>';
            else if (m.score === m.conceded) formHtml += '<div class="form-dot draw" title="Draw"></div>';
            else                            formHtml += '<div class="form-dot loss" title="Loss"></div>';
        });
        formHtml += '</div>';

        const gd = team.goalsFor - team.goalsAgainst;
        const gdClass = gd >= 0 ? 'positive' : 'negative';
        const lastDate = team.lastMatchDate ? formatDateShort(team.lastMatchDate) : '-';

        html += `<tr class="${zoneClass} ${highlighted}">
            <td class="position-cell">${team.position}</td>
            <td><img src="${team.badge || ''}" alt="${team.name}" class="team-logo" onerror="this.style.display='none'"></td>
            <td class="team-cell"><span class="team-name">${team.name}</span></td>
            <td class="points-cell">${team.points}</td>
            <td class="stat-cell">${team.played}</td>
            <td class="stat-cell hide-mobile">${team.wins}</td>
            <td class="stat-cell hide-mobile">${team.draws}</td>
            <td class="stat-cell hide-mobile">${team.losses}</td>
            <td class="stat-cell hide-mobile">${team.goalsFor}</td>
            <td class="stat-cell hide-mobile">${team.goalsAgainst}</td>
            <td class="goal-diff ${gdClass}">${gd > 0 ? '+' : ''}${gd}</td>
            <td class="stat-cell">${formHtml}</td>
            <td class="last-match-date hide-mobile">${lastDate}</td>
        </tr>`;
    });

    html += `</tbody></table>
        <div class="zone-legend">
            <div class="zone-legend-item"><div class="zone-legend-dot" style="background:var(--zone-lib)"></div><span>Libertadores (1–4)</span></div>
            <div class="zone-legend-item"><div class="zone-legend-dot" style="background:var(--zone-pre-lib)"></div><span>Libertadores qualifiers (5)</span></div>
            <div class="zone-legend-item"><div class="zone-legend-dot" style="background:var(--zone-sul)"></div><span>Sudamericana (6–11)</span></div>
            <div class="zone-legend-item"><div class="zone-legend-dot" style="background:var(--zone-rel)"></div><span>Relegation (17–20)</span></div>
        </div></div>`;
    return html;
}



