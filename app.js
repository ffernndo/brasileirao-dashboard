/**
 * Opens the progress overlay and starts data collection via SSE
 * (GET /update endpoint on the Flask server).
 */
function startUpdate() {
    const overlay = document.getElementById('updateOverlay');
    overlay.classList.remove('hidden');

    const bar     = document.getElementById('progressBar');
    const pctEl   = document.getElementById('progressPct');
    const msgEl   = document.getElementById('updateMessage');
    const closeBtn = document.getElementById('updateCloseBtn');

    if (IS_STATIC) {
        // GitHub Pages: data updated via GitHub Actions
        bar.style.width      = '100%';
        bar.style.background = 'var(--accent-green)';
        pctEl.textContent    = '✓';
        msgEl.textContent    = 'Data is updated automatically via GitHub Actions (daily at 7am BRT).';
        closeBtn.classList.remove('hidden');
        return;
    }

    bar.style.width      = '0%';
    bar.style.background = 'var(--accent-green)';
    pctEl.textContent    = '0%';
    msgEl.textContent    = 'Starting...';
    closeBtn.classList.add('hidden');

    const evtSource = new EventSource('/update');

    evtSource.onmessage = (e) => {
        const data = JSON.parse(e.data);
        const pct  = Math.max(0, data.progress);

        msgEl.textContent    = data.message;
        bar.style.width      = `${pct}%`;
        pctEl.textContent    = `${pct}%`;

        if (data.step === 'done') {
            evtSource.close();
            setTimeout(() => {
                overlay.classList.add('hidden');
                loadData();
            }, 1500);
        }
        if (data.step === 'error') {
            evtSource.close();
            bar.style.background = 'var(--accent-red)';
            closeBtn.classList.remove('hidden');
        }
    };

    evtSource.onerror = () => {
        evtSource.close();
        msgEl.textContent    = 'Connection error. Is the server running on localhost:5000?';
        bar.style.background = 'var(--accent-red)';
        closeBtn.classList.remove('hidden');
    };
}

