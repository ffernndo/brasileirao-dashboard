/**
 * Renders the standings charts (goals and points %).
 * Returns HTML and data for later Chart.js initialisation.
 *
 * @param {Array<TeamStats>} standings - Standings
 * @returns {{ html: string, goalsData: Object, performanceData: Object }}
 */
function renderCharts(standings) {
    const top10 = standings.slice(0, 10);

    const goalsData = {
        labels: top10.map(t => t.name),
        datasets: [
            { label: 'Gols Marcados', data: top10.map(t => t.goalsFor), backgroundColor: '#059669', borderRadius: 4 },
            { label: 'Gols Sofridos', data: top10.map(t => t.goalsAgainst), backgroundColor: '#dc2626', borderRadius: 4 }
        ]
    };

    const performanceData = {
        labels: standings.map(t => t.name),
        datasets: [{
            label: 'Points (%)',
            data: standings.map(t => {
                const p = t.played * 3;
                return p > 0 ? Math.round((t.points / p) * 100) : 0;
            }),
            backgroundColor: standings.map(t => {
                const p = t.played * 3;
                const perc = p > 0 ? (t.points / p) * 100 : 0;
                return perc >= 70 ? '#059669' : perc >= 50 ? '#d97706' : '#dc2626';
            }),
            borderRadius: 4
        }]
    };

    // Form table (last 5 for every team)
    let formTableHtml = `<div class="chart-wrapper" style="grid-column:1/-1">
        <h3 class="chart-title">Recent Form | Last 5 Matches</h3>
        <div class="form-table">
        <table class="standings-table"><thead><tr>
            <th>#</th><th>Team</th><th class="th-center">Pts</th><th class="th-center">P</th>
            <th class="th-center">Pts %</th><th class="th-center">Form</th>
        </tr></thead><tbody>`;
    standings.forEach(team => {
        const poss  = team.played > 0 ? Math.round(team.points / (team.played * 3) * 100) : 0;
        const color = poss >= 60 ? 'var(--accent-green)' : poss >= 40 ? 'var(--accent-yellow)' : 'var(--accent-red)';
        const last5 = [...team.matches]
            .sort((a, b) => new Date(b.date) - new Date(a.date))
            .slice(0, 5).reverse();
        const formDots = last5.map(m => {
            const res = m.score > m.conceded ? 'win' : m.score === m.conceded ? 'draw' : 'loss';
            return `<div class="form-dot ${res}"></div>`;
        }).join('');
        let zone = '';
        if (team.position <= 4)       zone = 'zone-libertadores';
        else if (team.position === 5) zone = 'zone-pre-libertadores';
        else if (team.position <= 11) zone = 'zone-sudamericana';
        else if (team.position >= 17) zone = 'zone-rebaixamento';
        formTableHtml += `<tr class="${zone}">
            <td class="position-cell">${team.position}</td>
            <td class="team-cell"><span class="team-name">${team.name}</span></td>
            <td class="points-cell">${team.points}</td>
            <td class="stat-cell">${team.played}</td>
            <td class="stat-cell" style="font-weight:700;color:${color}">${poss}%</td>
            <td class="stat-cell"><div class="form-dots">${formDots}</div></td>
        </tr>`;
    });
    formTableHtml += `</tbody></table></div></div>`;

    return {
        html: `
        <div class="charts-grid charts-grid--wide">
            ${formTableHtml}
        </div>
        <div class="charts-grid charts-grid--wide">
            <div class="chart-wrapper chart-wrapper--wide"><h3 class="chart-title">Points by Round (Top 6)</h3><div class="chart-container chart-container--tall"><canvas id="pointsProgressionChart"></canvas></div></div>
        </div>
        <div class="charts-grid">
            <div class="chart-wrapper"><h3 class="chart-title">Goals by Round</h3><div class="chart-container"><canvas id="goalsPerRoundChart"></canvas></div></div>
            <div class="chart-wrapper"><h3 class="chart-title">Results: Home vs Away</h3><div class="chart-container"><canvas id="homeAwayChart"></canvas></div></div>
        </div>
        <div class="charts-grid">
            <div class="chart-wrapper"><h3 class="chart-title">Goals Scored vs Conceded (Top 10)</h3><div class="chart-container"><canvas id="goalsChart"></canvas></div></div>
            <div class="chart-wrapper"><h3 class="chart-title">Home vs Away Performance (pts)</h3><div class="chart-container"><canvas id="homeAwayPtsChart"></canvas></div></div>
        </div>`,
        goalsData,
        performanceData
    };
}

/**
 * Renders the market values tab with KPIs, filters, table and charts.
 *
 * @returns {string} Full tab HTML
 */
function renderMarketValues() {
    const allPlayers = MARKET_VALUES_DATA.players;

    if (!allPlayers || allPlayers.length === 0) {
        return `<div class="market-empty">
            <div class="market-empty-icon">\uD83D\uDCB0</div>
            <div class="market-empty-title">Market Values</div>
            <div style="font-size:13px">Data is loading. Coming soon!</div>
        </div>`;
    }

    // Apply the header team filter
    const headerTeam = appState.selectedTeam;
    const players    = headerTeam !== 'All teams'
        ? allPlayers.filter(p => p.team === headerTeam)
        : allPlayers;

    if (players.length === 0) {
        return `<div class="market-empty">
            <div class="market-empty-icon">\uD83D\uDD0D</div>
            <div class="market-empty-title">${headerTeam}</div>
            <div style="font-size:13px">No players found for this team in the dataset.</div>
        </div>`;
    }

    const sorted = [...players].sort((a, b) => {
        const col = appState.mercadoSort || 'value';
        const dir = appState.mercadoSortDir === 'asc' ? 1 : -1;
        const va = a[col] ?? '';
        const vb = b[col] ?? '';
        if (typeof va === 'number') return (va - vb) * dir;
        return String(va).localeCompare(String(vb), 'pt-BR') * dir;
    });
    const teams = [...new Set(allPlayers.map(p => p.team))].sort();
    const positions = [...new Set(players.map(p => p.position))].sort();

    // Market KPIs, dynamic based on the filter
    const mostValuable = [...players].sort((a, b) => b.value - a.value)[0];
    const totalValue = players.reduce((s, p) => s + p.value, 0);
    const avgAge = players.length > 0 ? (players.reduce((s, p) => s + p.age, 0) / players.length).toFixed(1).replace('.', ',') : '-';

    let kpiHtml;
    if (headerTeam !== 'All teams') {
        // KPIs for the selected team
        kpiHtml = `<div class="kpi-grid">
            <div class="kpi-card"><div class="kpi-label">Most Valuable Player</div><div class="kpi-value small">${mostValuable.name}</div><div class="kpi-detail" style="color:var(--accent-green)">${formatMarketValue(mostValuable.value)}</div></div>
            <div class="kpi-card"><div class="kpi-label">Squad Value</div><div class="kpi-value small">${formatMarketValue(totalValue)}</div><div class="kpi-detail">${formatMarketValueBRL(totalValue)}</div></div>
            <div class="kpi-card"><div class="kpi-label">Average Age</div><div class="kpi-value">${avgAge}</div><div class="kpi-detail">years</div></div>
            <div class="kpi-card"><div class="kpi-label">Players</div><div class="kpi-value">${players.length}</div></div>
        </div>`;
    } else {
        // League-wide KPIs
        const teamValues = {};
        allPlayers.forEach(p => { teamValues[p.team] = (teamValues[p.team] || 0) + p.value; });
        const teamValArr = Object.entries(teamValues).sort((a, b) => b[1] - a[1]);
        const totalLeagueValue = allPlayers.reduce((s, p) => s + p.value, 0);
        kpiHtml = `<div class="kpi-grid">
            <div class="kpi-card"><div class="kpi-label">Most Valuable Player</div><div class="kpi-value small">${mostValuable.name}</div><div class="kpi-detail" style="color:var(--accent-green)">${formatMarketValue(mostValuable.value)} • ${mostValuable.team}</div></div>
            <div class="kpi-card"><div class="kpi-label">Most Valuable Squad</div><div class="kpi-value small">${teamValArr[0][0]}</div><div class="kpi-detail" style="color:var(--accent-green)">${formatMarketValue(teamValArr[0][1])}</div></div>
            <div class="kpi-card"><div class="kpi-label">Total League Value</div><div class="kpi-value small">${formatMarketValue(totalLeagueValue)}</div></div>
            <div class="kpi-card"><div class="kpi-label">Registered Players</div><div class="kpi-value">${allPlayers.length}</div></div>
        </div>`;
    }
    let html = kpiHtml;

    // Filters
    html += `<div class="market-controls">
        <input type="text" class="market-search" id="playerSearch" placeholder="Buscar jogador...">
        <select class="market-select" id="positionFilter"><option value="">All positions</option>${positions.map(p => `<option value="${p}">${p}</option>`).join('')}</select>
        <select class="market-select" id="marketTeamFilter"><option value="">All teams</option>${teams.map(t => `<option value="${t}">${t}</option>`).join('')}</select>
    </div>`;

    // Players table
    html += `<div class="market-table-wrapper"><table class="market-table" id="marketTable"><thead><tr>
        <th>#</th>
        <th class="sort-th" data-col="name">Player <span class="sort-icon">↕</span></th>
        <th class="sort-th th-center" data-col="team">Team <span class="sort-icon">↕</span></th>
        <th class="sort-th th-center" data-col="position">Pos <span class="sort-icon">↕</span></th>
        <th class="sort-th th-center" data-col="age">Age <span class="sort-icon">↕</span></th>
        <th class="sort-th th-center" data-col="value">Value (EUR) <span class="sort-icon">↕</span></th>
        <th class="th-center">Value (BRL)</th>
    </tr></thead><tbody>`;

    sorted.forEach((p, i) => {
        html += `<tr data-name="${p.name.toLowerCase()}" data-team="${p.team}" data-position="${p.position}">
            <td class="market-rank">${i + 1}</td>
            <td style="font-weight:500">${p.name}</td>
            <td class="stat-cell">${p.team}</td>
            <td class="stat-cell"><span class="market-position-badge">${p.position}</span></td>
            <td class="stat-cell">${p.age}</td>
            <td class="market-value-cell">${formatMarketValue(p.value)}</td>
            <td class="market-value-brl">${formatMarketValueBRL(p.value)}</td>
        </tr>`;
    });

    html += `</tbody></table></div>`;
    const rateNote = MARKET_VALUES_DATA.eur_brl_rate
        ? `Câmbio EUR/BRL: R$ ${MARKET_VALUES_DATA.eur_brl_rate.toFixed(2)}`
        : `Câmbio fixo: R$ ${EUR_TO_BRL.toFixed(2)}`;
    html += `<div class="market-source">Source: ${MARKET_VALUES_DATA.source} | Updated ${MARKET_VALUES_DATA.last_updated || MARKET_VALUES_DATA.lastUpdated} | ${rateNote}</div>`;

    // Charts
    html += `<div class="market-grid" style="margin-top:24px">
        <div class="chart-wrapper"><h3 class="chart-title">Squad Value by Team</h3><div class="chart-container"><canvas id="teamValuesChart"></canvas></div></div>
        <div class="chart-wrapper"><h3 class="chart-title">Distribution by Position</h3><div class="chart-container"><canvas id="positionValuesChart"></canvas></div></div>
    </div>`;

    return html;
}

